export const getInitialFormData = (): Record<string, string> => {
  const data: Record<string, string> = {};
  const collectKeys = (fields: RichField[]) => {
    fields.forEach((f) => {
      if (f.key) data[f.key] = "";
      if (f.subQuestions) collectKeys(f.subQuestions as RichField[]);
    });
  };
  collectKeys(formFields);
  return data;
};

