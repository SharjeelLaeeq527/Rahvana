// ─────────────────────────────────────────────────────────────
// ENUMS — matching Supabase ENUM types exactly
// ─────────────────────────────────────────────────────────────

/** All possible reminder trigger conditions */
export type ReminderType =
  | 'missing_document'           // required doc not uploaded
  | 'appointment_approaching'    // appointment within 14 days
  | 'police_certificate_pending' // PCC requested but not received
  | 'receipt_not_captured'       // filed but no USCIS receipt number saved
  | 'nvc_fee_not_confirmed'      // NVC fee step done but fee not posted
  | 'account_setup_incomplete'   // USCIS step done, no wallet record saved
  | 'ceac_upload_incomplete'     // CEAC upload step done, not confirmed
  | 'tool_session_abandoned'     // tool started 3+ days ago, incomplete
  | 'step_pending_too_long'      // step in-progress for 7+ days
  | 'appointment_not_recorded'   // appointment step complete, no date saved
  | 'ceac_status_update'         // CEAC status notification (Chapter 3, Step 9)

/** Priority levels — used for UI ordering and salience */
export type ReminderPriority = 'critical' | 'high' | 'normal' | 'low'

// ─────────────────────────────────────────────────────────────
// DATABASE ROW SHAPE
// ─────────────────────────────────────────────────────────────

/** A row in the journey_reminders table */
export interface JourneyReminder {
  id: string
  journey_id: string
  reminder_type: ReminderType
  priority: ReminderPriority
  title: string
  body: string
  step_key: string | null
  reference_id: string | null
  action_url: string | null
  action_label: string | null
  is_dismissed: boolean
  dismissed_at: string | null
  snoozed_until: string | null   // ISO timestamp — hide until this time
  dedup_key: string              // unique per journey+type+context
  created_at: string
  updated_at: string
}

// ─────────────────────────────────────────────────────────────
// ENGINE INPUT/OUTPUT
// ─────────────────────────────────────────────────────────────

/** Input to ReminderEngine.generateReminders() */
export interface ReminderGenerationContext {
  journeyId: string
}

/** A single reminder candidate generated by the engine (before DB upsert) */
export interface ReminderCandidate {
  reminder_type: ReminderType
  priority: ReminderPriority
  title: string
  body: string
  step_key?: string
  reference_id?: string
  action_url?: string
  action_label?: string
  dedup_key: string
}

// ─────────────────────────────────────────────────────────────
// API REQUEST / RESPONSE SHAPES
// ─────────────────────────────────────────────────────────────

/** Action to apply on PATCH /reminders/[reminderId] */
export type ReminderAction = 'dismiss' | 'snooze'

/** Body for PATCH /api/v1/journeys/[id]/reminders/[reminderId] */
export interface UpdateReminderBody {
  action: ReminderAction
  snooze_days?: number   // required when action = 'snooze', e.g. 1, 3, 7
}

/** GET /api/v1/journeys/[id]/reminders response */
export interface ReminderListResponse {
  success: true
  reminders: JourneyReminder[]
  total: number
  critical_count: number
  high_count: number
}

/** PATCH /api/v1/journeys/[id]/reminders/[id] response */
export interface ReminderUpdateResponse {
  success: true
  message: string
  reminder: JourneyReminder
}

